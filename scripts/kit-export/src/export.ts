function workspaceYaml(catalog: Record<string, string>): string {
  const lines = Object.keys(catalog)
    .sort()
    .map((name) => `  ${/^[a-z0-9-]+$/.test(name) ? name : JSON.stringify(name)}: ${catalog[name]}`);
  return [
    "packages:",
    "  - packages/*",
    "",
    "# Shared tool and library versions. Packages reference them as \"catalog:\".",
    "# pnpm pack writes the real versions into every published package.json.",
    "catalog:",
    ...lines,
    "",
    "# esbuild ships prebuilt binaries, so its postinstall is not needed.",
    "ignoredBuiltDependencies:",
    "  - esbuild",
    "",
  ].join("\n");
}

/** Names of the monorepo's internal design docs, which the kit must never mention. */
export function internalDocNames(repoRoot: string): string[] {
  const refs = join(repoRoot, ".claude/skills/bandwise-builder/references");
  const names = new Set<string>(DEFAULT_INTERNAL_DOC_NAMES);
  if (existsSync(refs)) {
    for (const f of walkFiles(refs)) names.add(f.split("/").pop() as string);
  }
  for (const f of existsSync(join(repoRoot, "docs")) ? walkFiles(join(repoRoot, "docs")) : []) {
    const base = f.split("/").pop() as string;
    // Plans, ADRs, runbooks and the backlog. A generic README.md stays allowed.
    if (base.endsWith(".md") && base !== "README.md") names.add(base);
  }
  return [...names].sort();
}

const isCode = (f: string): boolean => /\.(ts|tsx|js|mjs|cjs)$/.test(f);
const isTest = (f: string): boolean => /\.test\.tsx?$/.test(f);

function writeFile(outDir: string, rel: string, text: string): void {
  const full = join(outDir, rel);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, text);
}

/** Write the kit tree into `outDir`, then scan it. The report lists every change the export made. */
export function exportKit(options: ExportOptions): ExportReport {
  const repoRoot = resolve(options.repoRoot ?? REPO_ROOT);
  const outDir = resolve(options.outDir);
  prepareOutDir(outDir, repoRoot);
  const docNames = internalDocNames(repoRoot);

  const report: ExportReport = {
    outDir,
    files: [],
    excluded: [],
    moved: {},
    replacements: {},
    patches: [],
    droppedTests: [],
    rewrites: {},
    rewrittenFiles: [],
    findings: [],
  };
  const written = new Map<string, string>();
  const emit = (rel: string, text: string): void => {
    if (written.has(rel)) throw new Error(`kit export: ${rel} written twice`);
    written.set(rel, text);
  };

  const catalogSource = readCatalog(readFileSync(join(repoRoot, "pnpm-workspace.yaml"), "utf8"));
  const usedPatches = new Set<Patch>();
  const usedPhrases = new Set<(typeof PHRASES)[number]>();

  for (const src of gitFiles(repoRoot, [...SOURCES, ...Object.keys(MOVES)])) {
    const excluded = EXCLUDED.find((e) => e.re.test(src));
    if (excluded !== undefined) {
      report.excluded.push({ file: src, why: excluded.why });
      continue;
    }
    const dst = MOVES[src] ?? src;
    if (dst !== src) report.moved[src] = dst;
    let text = readFileSync(join(repoRoot, src), "utf8");

    const pkgMatch = /^packages\/([^/]+)\/package\.json$/.exec(src);
    if (pkgMatch !== null) {
      const dir = pkgMatch[1] as string;
      emit(dst, `${JSON.stringify(kitManifest(JSON.parse(text) as Json, dir, KIT_VERSION), null, 2)}\n`);
      continue;
    }

    for (const r of GLOBAL_REPLACEMENTS) {
      const count = text.split(r.find).length - 1;
      if (count > 0) {
        text = text.split(r.find).join(r.replace);
        report.replacements[r.find] = (report.replacements[r.find] ?? 0) + count;
      }
    }
    for (const p of PATCHES.filter((p) => p.file === src)) {
      const count = text.split(p.find).length - 1;
      if (count !== 1) throw new Error(`kit export: patch for ${src} matched ${count} times, expected 1 (${p.why})`);
      text = text.replace(p.find, () => p.replace);
      usedPatches.add(p);
      report.patches.push({ file: src, why: p.why });
    }
    if (isCode(src)) {
      for (const ph of PHRASES) {
        const count = text.split(ph.find).length - 1;
        if (count > 0) {
          text = text.split(ph.find).join(ph.replace);
          usedPhrases.add(ph);
        }
      }
    }
    const drop = DROPPED_TESTS[src];
    if (drop !== undefined) {
      const res = dropTests(text, src, drop);
      text = res.text;
      for (const title of res.dropped) report.droppedTests.push({ file: src, title });
    }
    if (isCode(src)) {
      const before = text;
      text = rewriteComments(text, src, { internalDocNames: docNames }, report.rewrites);
      if (isTest(src)) text = rewriteTestTitles(text, src, { internalDocNames: docNames }, report.rewrites);
      if (text !== before) report.rewrittenFiles.push(dst);
    }
    emit(dst, text);
  }
  const unusedPhrases = PHRASES.filter((p) => !usedPhrases.has(p));
  if (unusedPhrases.length > 0) throw new Error(`kit export: comment phrases no longer found: ${unusedPhrases.map((p) => JSON.stringify(p.find)).join(", ")}`);
  const unused = PATCHES.filter((p) => !usedPatches.has(p));
  if (unused.length > 0) throw new Error(`kit export: patches for missing files: ${unused.map((p) => p.file).join(", ")}`);
  for (const file of Object.keys(DROPPED_TESTS)) {
    if (!report.droppedTests.some((d) => d.file === file)) throw new Error(`kit export: ${file} was not exported`);
  }

  // Hand-written kit files: license, community docs, workflows and the kit's own config package.
  for (const rel of walkFiles(OVERLAY_DIR)) emit(rel, readFileSync(join(OVERLAY_DIR, rel), "utf8"));

  // The TypeScript base, from the monorepo's shared config. It lives in the config package, next
  // to library.json: Vite's tsconfig loader does not follow an extends that leaves a symlinked package.
  const base = JSON.parse(readFileSync(join(repoRoot, "packages/config/tsconfig/base.json"), "utf8")) as Json;
  base["display"] = "Bandwise kit base";
  emit("packages/config/tsconfig/base.json", `${JSON.stringify(base, null, 2)}\n`);

  // Per package: README and LICENSE, so npm shows them.
  const license = readFileSync(join(OVERLAY_DIR, "LICENSE"), "utf8");
  for (const dir of PUBLISHED_PACKAGES) {
    emit(`packages/${dir}/README.md`, packageReadme(dir, `@bandwise/${dir}`));
    emit(`packages/${dir}/LICENSE`, license);
  }

  // Root manifest, workspace and catalog of only what the kit uses.
  emit("package.json", `${JSON.stringify(rootManifest(), null, 2)}\n`);
  const kitNames = new Set<string>();
  const needed = new Set<string>();
  const manifests = [...written.entries()].filter(([f]) => /^packages\/[^/]+\/package\.json$/.test(f));
  for (const [, text] of manifests) kitNames.add((JSON.parse(text) as Json)["name"] as string);
  for (const [file, text] of manifests) {
    for (const [name, spec] of Object.entries(depsOf(JSON.parse(text) as Json))) {
      if (spec.startsWith("workspace:") && !kitNames.has(name)) throw new Error(`kit export: ${file} needs ${name}, which is not in the kit`);
      if (spec === "catalog:") needed.add(name);
      else if (spec.startsWith("catalog:")) throw new Error(`kit export: named catalogs are not supported (${file} ${name})`);
    }
  }
  const catalog: Record<string, string> = {};
  for (const name of needed) {
    const v = catalogSource[name];
    if (v === undefined) throw new Error(`kit export: ${name} is not in the monorepo catalog`);
    catalog[name] = v;
  }
  emit("pnpm-workspace.yaml", workspaceYaml(catalog));

  const templates: ReadmeTemplate[] = TEMPLATES.map((t) => ({
    id: t.id,
    title: t.title,
    job: t.job,
    questions: t.spec.stages.flatMap((s) => Object.keys(s.questions)),
  }));
  emit("README.md", kitReadme(templates));

  for (const [rel, text] of written) writeFile(outDir, rel, text);
  report.files = [...written.keys()].sort();

  if (options.lockfile === true) {
    execFileSync("pnpm", ["install", "--lockfile-only"], { cwd: outDir, stdio: "inherit" });
  }

  report.findings = scanTree(outDir, { internalDocNames: docNames });
  return report;
}

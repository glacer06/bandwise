type Json = Record<string, unknown>;

const toPosix = (p: string): string => p.split(sep).join("/");

function gitFiles(repoRoot: string, paths: readonly string[]): string[] {
  const out = execFileSync("git", ["ls-files", "-z", "--cached", "--others", "--exclude-standard", "--", ...paths], {
    cwd: repoRoot,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  return [...new Set(out.split("\0").filter((f) => f !== ""))].filter((f) => existsSync(join(repoRoot, f))).sort();
}

function walkFiles(dir: string, base = dir): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir).sort()) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...walkFiles(full, base));
    else out.push(toPosix(relative(base, full)));
  }
  return out;
}

/** Empty the output folder, keeping .git and pnpm-lock.yaml. Refuses folders that look wrong. */
function prepareOutDir(outDir: string, repoRoot: string): void {
  const out = resolve(outDir);
  const root = resolve(repoRoot);
  if (out === root || root.startsWith(`${out}${sep}`)) throw new Error(`kit export: refusing to write into ${out}, which holds the monorepo`);
  if (out.startsWith(`${root}${sep}`) && !out.startsWith(`${join(root, "dist-kit")}`)) {
    throw new Error(`kit export: inside the monorepo the output must be under dist-kit/, not ${out}`);
  }
  if (!existsSync(out)) {
    mkdirSync(out, { recursive: true });
    return;
  }
  const entries = readdirSync(out);
  if (entries.length === 0) return;
  const pkgPath = join(out, "package.json");
  const isKit = existsSync(pkgPath) && (JSON.parse(readFileSync(pkgPath, "utf8")) as Json)["name"] === "bandwise-kit";
  if (!isKit && !entries.includes(".git")) {
    throw new Error(`kit export: ${out} is not empty and is not a bandwise-kit checkout; pick an empty folder`);
  }
  for (const entry of entries) {
    if (entry === ".git" || entry === "pnpm-lock.yaml") continue;
    rmSync(join(out, entry), { recursive: true, force: true });
  }
}

/** The monorepo's pnpm catalog, name to version. */
export function readCatalog(workspaceYaml: string): Record<string, string> {
  const catalog: Record<string, string> = {};
  let inside = false;
  for (const raw of workspaceYaml.split("\n")) {
    if (/^catalog:\s*$/.test(raw)) {
      inside = true;
      continue;
    }
    if (!inside) continue;
    if (/^\S/.test(raw)) break;
    const line = raw.trim();
    if (line === "" || line.startsWith("#")) continue;
    const m = /^"?([^":]+)"?:\s*(\S+)\s*$/.exec(line);
    if (m !== null) catalog[m[1] as string] = m[2] as string;
  }
  return catalog;
}

function depsOf(manifest: Json): Record<string, string> {
  const all: Record<string, string> = {};
  for (const field of ["dependencies", "devDependencies", "peerDependencies"]) {
    const deps = manifest[field] as Record<string, string> | undefined;
    if (deps !== undefined) Object.assign(all, deps);
  }
  return all;
}

/** The kit version of a package manifest. */
export function kitManifest(source: Json, dir: string, version: string): Json {
  const m: Json = structuredClone(source);
  delete m["private"];
  m["version"] = version;
  const description = PACKAGE_DESCRIPTIONS[dir];
  if (description === undefined) throw new Error(`kit export: no description for packages/${dir}`);
  m["description"] = description;
  m["license"] = "Apache-2.0";
  m["keywords"] = KEYWORDS;
  m["homepage"] = KIT_HOMEPAGE;
  m["repository"] = { type: "git", url: `git+https://github.com/${KIT_REPO}.git`, directory: `packages/${dir}` };
  m["bugs"] = { url: `https://github.com/${KIT_REPO}/issues` };
  m["engines"] = { node: ">=22" };
  m["publishConfig"] = { access: "public", provenance: true };

  const exports = m["exports"] as Json | undefined;
  if (exports !== undefined) delete exports["./openapi.json"];
  const files = m["files"] as string[] | undefined;
  if (files !== undefined) m["files"] = files.filter((f) => f !== "openapi.json" && f !== "contract");

  if (dir === "cli") {
    // In the kit the CLI's only command is local mode, so core and the fixture transport are
    // real dependencies. As optional peers, `npx @bandwise/cli` would not install them.
    const peers = (m["peerDependencies"] ?? {}) as Record<string, string>;
    const deps = (m["dependencies"] ?? {}) as Record<string, string>;
    const dev = (m["devDependencies"] ?? {}) as Record<string, string>;
    for (const name of Object.keys(peers)) deps[name] = peers[name] as string;
    m["dependencies"] = Object.fromEntries(Object.entries(deps).sort(([a], [b]) => a.localeCompare(b)));
    m["devDependencies"] = Object.fromEntries(Object.entries(dev).filter(([name]) => !(name in peers)));
    delete m["peerDependencies"];
    delete m["peerDependenciesMeta"];
  }

  // Keep a stable, readable key order.
  const order = [
    "name",
    "version",
    "description",
    "keywords",
    "homepage",
    "bugs",
    "license",
    "repository",
    "type",
    "bin",
    "exports",
    "files",
    "engines",
    "publishConfig",
    "scripts",
    "dependencies",
    "peerDependencies",
    "peerDependenciesMeta",
    "devDependencies",
  ];
  const sorted: Json = {};
  for (const k of order) if (k in m) sorted[k] = m[k];
  for (const k of Object.keys(m)) if (!(k in sorted)) sorted[k] = m[k];
  return sorted;
}

